def run_PSO(t, I_data, R_data, N, gens=500, pop_size=50):
    pos = np.random.rand(pop_size, 2)
    vel = np.zeros_like(pos)
    pbest = pos.copy()
    gbest = min(pbest, key=lambda p: mse_sir(p, t, I_data, R_data, N, I_data[0], R_data[0]))

    beta_hist, gamma_hist, mse_hist = [], [], []

    for g in range(gens):
        for i in range(pop_size):
            vel[i] = 0.5*vel[i] + 1.5*np.random.rand()*(pbest[i]-pos[i]) + \
                     1.5*np.random.rand()*(gbest-pos[i])
            pos[i] = np.clip(pos[i] + vel[i], 0.01, 1.0)

            if mse_sir(pos[i], t, I_data, R_data, N, I_data[0], R_data[0]) < \
               mse_sir(pbest[i], t, I_data, R_data, N, I_data[0], R_data[0]):
                pbest[i] = pos[i]

        gbest = min(pbest, key=lambda p: mse_sir(p, t, I_data, R_data, N, I_data[0], R_data[0]))
        beta_hist.append(gbest[0])
        gamma_hist.append(gbest[1])
        mse_hist.append(mse_sir(gbest, t, I_data, R_data, N, I_data[0], R_data[0]))

    return mse_hist, beta_hist, gamma_hist

