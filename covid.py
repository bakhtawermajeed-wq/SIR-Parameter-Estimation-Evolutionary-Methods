def sir_model(y, t, beta, gamma, N):
    S, I, R = y
    dS = -beta * S * I / N
    dI = beta * S * I / N - gamma * I
    dR = gamma * I
    return [dS, dI, dR]

def mse_sir(params, t, I_data, R_data, N, I0, R0):
    beta, gamma = params
    if beta <= 0 or gamma <= 0:
        return 1e10

    S0 = N - I0 - R0
    sol = odeint(sir_model, [S0, I0, R0], t, args=(beta, gamma, N))
    I_pred, R_pred = sol[:,1], sol[:,2]
    return np.mean((I_pred - I_data)**2 + (R_pred - R_data)**2)

def run_DE(t, I_data, R_data, N, gens=500, pop_size=50):
    bounds = [(0.01, 1.0), (0.01, 1.0)]
    pop = np.random.rand(pop_size, 2)
    pop[:,0] = bounds[0][0] + pop[:,0]*(bounds[0][1]-bounds[0][0])
    pop[:,1] = bounds[1][0] + pop[:,1]*(bounds[1][1]-bounds[1][0])

    beta_hist, gamma_hist, mse_hist = [], [], []

    for g in range(gens):
        for i in range(pop_size):
            idxs = [idx for idx in range(pop_size) if idx != i]
            a, b, c = pop[np.random.choice(idxs, 3, replace=False)]
            F, CR = 0.8, 0.9

            mutant = np.clip(a + F*(b - c), 0.01, 1.0)
            trial = np.where(np.random.rand(2) < CR, mutant, pop[i])

            if mse_sir(trial, t, I_data, R_data, N, I_data[0], R_data[0]) < \
               mse_sir(pop[i], t, I_data, R_data, N, I_data[0], R_data[0]):
                pop[i] = trial

        best = pop[np.argmin([mse_sir(p, t, I_data, R_data, N, I_data[0], R_data[0]) for p in pop])]
        beta_hist.append(best[0])
        gamma_hist.append(best[1])
        mse_hist.append(mse_sir(best, t, I_data, R_data, N, I_data[0], R_data[0]))

    return mse_hist, beta_hist, gamma_hist

